// Project adaptation of unmodified, hash-pinned Microchip device definitions.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
const vendor=new URL('../vendor/microchip/ATtiny_DFP/3.4.278/',import.meta.url);
const provenance=JSON.parse(readFileSync(new URL('provenance.json',vendor)));
const read=name=>{
  const data=readFileSync(new URL(name,vendor)),record=provenance.files[name];
  assert.equal(data.length,record.bytes,name);
  assert.equal(createHash('sha256').update(data).digest('hex'),record.sha256,name);
  return data.toString('utf8');
};
const header=read('include/avr/iotn88.h'),atdf=read('atdf/ATtiny88.atdf'),assembler=read('avrasm/inc/tn88def.inc');
const attrs=s=>Object.fromEntries([...s.matchAll(/([\w-]+)="([^"]*)"/g)].map(m=>[m[1],m[2]]));
const registers=new Map([...atdf.matchAll(/<register\s+([^>]+)>/g)].map(m=>{const a=attrs(m[1]);return[a.name,a];}));
const data={},bits={};
const ioOffset=Number(registers.get('TIFR1').offset)-Number(header.match(/#define\s+TIFR1\s+_SFR_IO8\(([^)]+)\)/)[1]);
for(const m of header.matchAll(/^#define\s+(\w+)\s+_SFR_(IO|MEM)(?:8|16)\(([^)]+)\)/gm)){
  data[m[1]]=Number(m[3])+(m[2]==='IO'?ioOffset:0);
  if(registers.has(m[1]))assert.equal(data[m[1]],Number(registers.get(m[1]).offset),m[1]);
}
for(const name of ['SREG','SPL','SPH']){
  data[name]=Number(registers.get(name).offset);
  const asm=assembler.match(new RegExp('^\\.equ\\s+'+name+'\\s*=\\s*(0x[\\da-f]+)','mi'));
  assert.equal(Number(asm[1])+ioOffset,data[name],name);
}
for(const name of ['SE','TOV1','WDE','WDIE'])bits[name]=Number(header.match(new RegExp('^#define\\s+'+name+'\\s+([0-7])\\s*$','m'))[1]);
const segment=name=>attrs([...atdf.matchAll(/<memory-segment\s+([^>]+)\/>/g)].map(m=>m[1]).find(s=>attrs(s).name===name));
const flash=segment('FLASH'),ram=segment('IRAM');
const memory={flashBytes:Number(flash.size),ramStart:Number(ram.start),ramEnd:Number(ram.start)+Number(ram.size)-1,ioOffset,spHighMask:Number(registers.get('SPH').mask)};
for(const [macro,value] of [['FLASHEND',memory.flashBytes-1],['RAMSTART',memory.ramStart],['RAMEND',memory.ramEnd]])
  assert.equal(Number(header.match(new RegExp('^#define\\s+'+macro+'\\s+([^\\s]+)','m'))[1].replace(/[()]/g,'')),value,macro);
const output='// Generated by scripts/generate-attiny88-registers.mjs from Microchip ATtiny_DFP 3.4.278.\n'+
  Object.entries({AT88_DATA:data,AT88_BITS:bits,AT88_MEMORY:memory}).map(([name,map])=>'export const '+name+'=Object.freeze('+JSON.stringify(map,null,2)+');\n').join('');
const target=new URL('../lib/attiny88-registers.js',import.meta.url);
if(process.argv.includes('--check'))assert.equal(readFileSync(target,'utf8').replaceAll('\r\n','\n'),output,'Stale ATtiny88 definitions');
else writeFileSync(target,output);
