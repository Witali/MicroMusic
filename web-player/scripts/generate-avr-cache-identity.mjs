// Hash the host/compiler source graph; exclude only this generated result.
import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {parseArgs} from 'node:util';
const root=fileURLToPath(new URL('../../',import.meta.url));
const output='web-player/lib/avr-cache-identity.js';
const {values}=parseArgs({options:{check:{type:'boolean'}}});
const hash=b=>createHash('sha256').update(b).digest('hex');
function files(dir){return readdirSync(join(root,dir),{withFileTypes:true}).flatMap(e=>
  e.isDirectory()?files(dir+'/'+e.name):e.name.endsWith('.js')?[dir+'/'+e.name]:[]);}
const inputs=[...files('web-player/lib').filter(p=>p!==output),'web-player/scripts/generate-avr-cache-identity.mjs'].sort();
const sources=Object.fromEntries(inputs.map(p=>[p,hash(readFileSync(join(root,p),'utf8').replaceAll('\r\n','\n'))]));
const id=hash(JSON.stringify(sources));
const source='// Generated by scripts/generate-avr-cache-identity.mjs. Do not edit.\n'+
  `export const AVR_CACHE_COMPILER_ID=${JSON.stringify(id)};\n`+
  `export const AVR_CACHE_SOURCES=Object.freeze(${JSON.stringify(sources,null,2)});\n`;
if(values.check){if(readFileSync(join(root,output),'utf8').replaceAll('\r\n','\n')!==source)throw Error('Stale AVR cache identity; run node web-player/scripts/generate-avr-cache-identity.mjs');}
else writeFileSync(join(root,output),source);
console.log(`${values.check?'Checked':'Generated'} AVR cache identity ${id}, ${inputs.length} sources`);
