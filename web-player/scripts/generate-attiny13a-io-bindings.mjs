// Project ownership bindings, separate from the original manufacturer inputs.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {AT13_IO} from '../lib/attiny13a-registers.js';
const dir=new URL('../native/devices/attiny13a/',import.meta.url);
const source=readFileSync(new URL('io_registers.inc',dir),'utf8');
const entries=[...source.matchAll(/^AT13_IO_(PUBLISH|LOCAL)\(([A-Z0-9_]+),\s*([A-Z0-9_]+)(?:,\s*(.*))?\)$/gm)]
  .map(([,kind,owner,name,value])=>({kind,owner,name,value,address:AT13_IO[name]}));
assert.equal(entries.length,source.split(/\r?\n/).filter(line=>line.startsWith('AT13_IO_')).length,'Invalid binding syntax');
const owners=new Set(['ADC','COMPARATOR','GPIO','WATCHDOG','NVM','BOARD','TIMER0','CLOCK','CPU','DEBUG']);
for(const e of entries){
  assert.ok(owners.has(e.owner),'Unknown owner '+e.owner);assert.ok(Object.hasOwn(AT13_IO,e.name),'Unknown manufacturer register '+e.name);
  assert.equal(e.value!==undefined,e.kind==='PUBLISH','Invalid publication binding '+e.name);
}
assert.equal(new Set(entries.map(e=>e.address)).size,entries.length,'Duplicate byte owner (including aliases)');
assert.deepEqual(entries.map(e=>e.address).sort((a,b)=>a-b),[...new Set(Object.values(AT13_IO))].sort((a,b)=>a-b),'Incomplete manufacturer I/O coverage');
const timer=entries.filter(e=>e.owner==='TIMER0');assert.ok(timer.length);
const output='/* Generated by scripts/generate-attiny13a-io-bindings.mjs; do not edit. */\n'+
  '#ifndef MICROMUSIC_ATTINY13A_IO_BINDINGS_H\n#define MICROMUSIC_ATTINY13A_IO_BINDINGS_H\n'+
  '#define AT13_IO_IS_TIMER0(io) ('+timer.map(e=>'(io)==AT13_IO_'+e.name).join(' || ') +')\n#endif\n';
const path=new URL('io_registers.generated.h',dir);
if(process.argv.includes('--check'))assert.equal(readFileSync(path,'utf8').replaceAll('\r\n','\n'),output,'Stale generated I/O bindings');
else writeFileSync(path,output);
console.log(`ATtiny13A I/O bindings: ${entries.length} byte owners, ${entries.filter(e=>e.kind==='PUBLISH').length} publications, ${timer.length} Timer0 routes`);
