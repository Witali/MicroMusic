import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {controlRatios} from '../../scripts/lib/runtime-control-design.mjs';
const read=name=>readFileSync(new URL(name,import.meta.url),'utf8').replaceAll('\r\n','\n');
const json=name=>JSON.parse(read(name)),sha=s=>createHash('sha256').update(s).digest('hex');
const root=fileURLToPath(new URL('../../../',import.meta.url));
const initial=json('initial-screen.json'),cached=json('cached-screen.json'),validation=json('validation.json');
for(const [report,file]of [[initial,'initial-sources.json'],[cached,'cached-sources.json'],[validation,'validation-sources.json']]){
  assert.equal(report.complete,true);assert.equal(report.transform,'phase-locals');
  const sources=json(file);for(const [path,hash]of Object.entries(report.sourceSha256))assert.equal(sha(sources[path]),hash,path);
  for(const [path,hash]of Object.entries(report.baseline.sourceSha256))
    assert.equal(sha(execFileSync('git',['show',report.baseline.revision+':'+path],{cwd:root,encoding:'utf8'}).replaceAll('\r\n','\n')),hash,path);
  assert.equal(sha(execFileSync('git',['show',report.baseline.revision+':web-player/wasm/attiny13a.wasm'],{cwd:root,maxBuffer:1024*1024})),report.runtimeSha256);
}
assert.equal(initial.cases.length,2);assert.equal(cached.cases.length,2);
assert.equal(cached.cpuModulePolicy,'production-translation-cache');assert.equal(cached.gcBeforeRun,true);
assert.equal(cached.trials,16);assert.equal(cached.warmups,8);
const totals={timed:0,warmups:0,checkpoints:0};
for(const report of [initial,cached])for(const row of report.cases){
  assert.ok(['rhythmic-physical','hq4-chego-auto-physical'].includes(row.id));
  assert.deepEqual(controlRatios(row.runs,report.trials),row.ratios);
  assert.equal(row.runs.length,4*report.trials);assert.equal(row.warmups.length,4*report.warmups);
  totals.timed+=row.runs.length;totals.warmups+=row.warmups.length;
  totals.checkpoints+=[...row.runs,...row.warmups].reduce((n,r)=>n+r.checkpoints,0);
  const final=validation.cases.find(c=>c.id===row.id);assert.ok(final);
  for(const key of ['inputSha256','outputSha256'])assert.equal(row.optimization[key],final.optimization[key],'Final/initial generated bytes must match');
}
const expected=['rhythmic-compatible','rhythmic-physical','lumiere-stereo-compatible','lumiere-stereo-physical',
  'hq4-chego-auto-compatible','hq4-chego-auto-physical','kernel-compatible-direct','kernel-physical-direct',
  'kernel-clki-20m-div1','kernel-clki-20m-div256','kernel-internal-20m-div1',
  'kernel-internal-20m-div1-adc-active','kernel-clki-20m-div1-adc-active'];
assert.deepEqual(validation.cases.map(c=>c.id),expected);assert.equal(validation.mode,'validation');
let runs=0,checkpoints=0;
for(const row of validation.cases){
  assert.equal(row.runs.length,2);runs+=2;checkpoints+=row.runs.reduce((n,r)=>n+r.checkpoints,0);
  const stats=row.optimization.phaseLocals;
  if(stats){assert.ok(stats.liveSlots<stats.fullSlots);assert.equal(stats.fullSlots,10*stats.waitSites);assert.ok(row.optimization.outputBytes<row.optimization.inputBytes);}
  else assert.equal(row.optimization.outputSha256,row.optimization.inputSha256);
}
for(const report of [initial,cached,validation])for(const row of report.cases){
  const observations=[...row.runs,...row.warmups],first=observations[0];
  for(const run of observations)for(const key of ['rawSha256','stateSha256','pinSha256','checkpoints'])assert.equal(run[key],first[key]);
}
assert.deepEqual(totals,{timed:192,warmups:96,checkpoints:3456});assert.deepEqual([runs,checkpoints],[26,168]);
const tap=read('full-test.tap');for(const line of ['tests 1649','pass 1649','fail 0','skipped 0'])assert.ok(tap.includes('# '+line+'\n'));
console.log(JSON.stringify({...totals,validationRuns:runs,validationCheckpoints:checkpoints,tests:1649}));
