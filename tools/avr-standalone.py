"""Bundle the shared AVR core and profiles for downloadable offline players.

Only this explicit, dependency-ordered module list is bundled. Source hashes
use UTF-8 with LF line endings so artifacts reproduce on Windows and Unix.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ('web-player/lib/avr-profiles.js', 'web-player/lib/avr-reference.js',
           'web-player/lib/hex.js')


def source_hashes():
    return {name: hashlib.sha256((ROOT/name).read_text(encoding='utf-8').encode()).hexdigest()
            for name in SOURCES}


def record_sources(report):
    hashes = source_hashes()
    report['standaloneCoreSources'] = dict(normalization='UTF-8, LF', sha256=hashes)
    if 'standaloneCoreSourceSha256' in report:
        report['standaloneCoreSourceSha256'] = hashes[SOURCES[1]]
        report['standaloneHexParserSourceSha256'] = hashes[SOURCES[2]]
    return report


def bundle_core():
    parts = ['// Generated by tools/avr-standalone.py; edit the shared source modules.\n']
    for name in SOURCES:
        text = (ROOT/name).read_text(encoding='utf-8')
        text = re.sub(r'^import .*?;\s*$', '', text, flags=re.M)
        text = re.sub(r'^export \{[^\n]*\};\s*$', '', text, flags=re.M)
        text = re.sub(r'^export (?=(?:const|let|function|class)\b)', '', text, flags=re.M)
        if re.search(r'^\s*(?:import|export)\b', text, flags=re.M):
            raise ValueError(f'Unsupported module declaration in {name}')
        parts.append('// '+name+'\n'+text.rstrip()+'\n')
    parts.append('''
AVRCore.fromHex=(flash,eeprom,options={})=>{
  const profile=resolveAVRProfile(options.target);
  return new AVRCore(parseHex(flash,profile.flashBytes),
    eeprom?parseHex(eeprom,profile.eepromBytes):null,options);
};
if(typeof module!=='undefined'&&module.exports)
  module.exports={AVRCore,AVR_PROFILES,resolveAVRProfile};
''')
    return '\n'.join(parts)


def save_core(folder):
    core = bundle_core()
    (Path(folder)/'avr_core.js').write_text(core, encoding='utf-8', newline='\n')
    return core


def refresh(folder):
    """Refresh only emulator assets/provenance, preserving the firmware bytes."""
    folder = Path(folder)
    old = (folder/'avr_core.js').read_text(encoding='utf-8')
    html = (folder/'player.html').read_text(encoding='utf-8')
    if html.count(old) != 1:
        raise ValueError(f'{folder}: embedded core is missing or ambiguous')
    core = save_core(folder)
    (folder/'player.html').write_text(html.replace(old, core), encoding='utf-8', newline='\n')
    report_file = folder/'build-report.json'
    report = record_sources(json.loads(report_file.read_text(encoding='utf-8')))
    report_file.write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n',
                           encoding='utf-8', newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('folders', nargs='+', type=Path)
    for folder in parser.parse_args().folders:
        refresh(folder)
        print(f'{folder.name}: shared AVR core refreshed; firmware unchanged')
