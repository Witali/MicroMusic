#!/usr/bin/env python3
"""Generate a constant-cycle, ROM-only Z80 PWM player (ORG 0).
The PC supplies 0..254 quantized indices. FF terminates and holds centre.
D4 on I/O 1000h. No stack accesses, RAM or interrupts. 320 T per pulse.
"""
from pathlib import Path
from functools import lru_cache
import argparse, json, struct
import numpy as np
ROOT=Path(__file__).resolve().parent
W=[35,100,135,145,150,160,170,175,185,220,285]

class Image:
 def __init__(self):self.b=bytearray();self.lines=['; Generated by build_pwm.py. Z80, org 0.','    org 0'];self.labels={};self.fix=[];self.serial=0
 @property
 def pc(self):return len(self.b)
 def label(self,s):assert s not in self.labels;self.labels[s]=self.pc;self.lines.append(s+':')
 def unique(self,s):self.serial+=1;return f'{s}_{self.serial}'
 def op(self,s,*v):self.lines.append('    '+s);self.b.extend(v)
 def addr(self,s,op,label):self.lines.append('    '+s+' '+label);self.b.extend(op);self.fix.append((self.pc,label));self.b.extend(b'\0\0')
 def jp(self,label,cond=''):
  self.addr('jp '+cond+',' if cond else 'jp',bytes([{'':0xc3,'z':0xca,'nc':0xd2}[cond]]),label)
 def data(self,v):
  v=bytes(v);self.b.extend(v)
  for p in range(0,len(v),16):self.lines.append('    db '+','.join(f'${x:02x}' for x in v[p:p+16]))
 def align(self,n):self.data(bytes((-self.pc)%n))
 def finish(self):
  for a,s in self.fix:struct.pack_into('<H',self.b,a,self.labels[s])
  return bytes(self.b)

# All padding preserves A, F, BC, DE, HL and IY. EXX/DJNZ uses only B'.
# SP is unused, so INC SP is safe; no memory access. Avoid LD I/R changes.
@lru_cache(None)
def pad(t):
 if t==0:return (0,())
 if t<0:return None
 opts=[(4,1,'nop'),(6,1,'inc sp'),(7,2,'ld b,16'),(12,2,'jr')]+[(13*n+10,6,n) for n in range(1,23)]
 ans=[]
 for a,c,s in opts:
  q=pad(t-a)
  if q is not None:ans.append((c+q[0],(s,)+q[1]))
 return min(ans,key=lambda x:x[0]) if ans else None

def emitpad(im,p):
 for a in p:
  if a=='nop':im.op('nop',0)
  elif a=='inc sp':im.op('inc sp',0x33)
  elif a=='ld b,16':im.op('ld b,16',0x06,16)
  elif a=='jr':im.op('jr $+2',0x18,0)
  else:im.op('exx',0xd9);im.op(f'ld b,{a}',0x06,a);im.op('djnz $',0x10,0xfe);im.op('exx',0xd9)

# pattern data at 0100h..02ffh; 128 positive patterns, transposed by pair.
# 0300h/0400h: dispatch addresses, 8 phases * 32 entries (sign and width).
PAT=1;DISP=3;MAP=5;FRAC=7;MODE="index"

def code(t,s,*b):return (t,s,b)
def pcm_prefetch():
 return [code(19,'ld a,(iy+0)',0xfd,0x7e,0),code(4,'ld l,a',0x6f),code(7,f'ld h,{MAP}',0x26,MAP),code(7,'ld a,(hl)',0x7e),code(8,'ld ixl,a',0xdd,0x6f),code(4,'inc h',0x24),code(7,'ld a,(hl)',0x7e),code(8,'ld ixh,a',0xdd,0x67),code(19,'ld a,(iy+1)',0xfd,0x7e,1),code(4,"ex af,af'",8)]
def pcm_complete():
 return [code(4,"ex af,af'",8),code(7,'cp 4',0xfe,4),(82,'pcm_quant',()),code(4,"ex af,af'",8)]

def next_sample():
 if MODE=='pcm10':a=[code(4,"ex af,af'",8)]
 else:a=[code(19,'ld a,(iy+0)',0xfd,0x7e,0),code(7,'cp 255',0xfe,255),(34,'eos34',())]
 return a+[code(7,'sub 127',0xd6,127),(35,'sign',()),code(4,'ld e,a',0x5f)]

def lookup(p):
 a=[code(4,'ld a,e',0x7b)]
 if p//2&1:a.append(code(7,'or 128',0xf6,128))
 a += [code(4,'ld l,a',0x6f),code(7,f'ld h,{PAT+p//4}',0x26,PAT+p//4),code(7,'ld a,(hl)',0x7e)]
 if not p&1:a += [code(4,'rrca',0x0f)]*4
 a += [code(7,'and 15',0xe6,15),code(4,'or d',0xb2)]
 if p:a.append(code(7,f'or {p*32}',0xf6,p*32))
 a += [code(4,'ld l,a',0x6f),code(7,f'ld h,{DISP}',0x26,DISP),code(7,'ld a,(hl)',0x7e),code(4,'inc h',0x24),code(7,'ld h,(hl)',0x66),code(4,'ld l,a',0x6f),code(4,'jp (hl)',0xe9)]
 return a

def emit(im,a):
 t,s,b=a
 if b:im.op(s,*b);return
 if s=='eos':
  # A=255 is an EOS byte, held forever. Both paths 30T.
  # normal: jp z (10), inc iy (10), jp join (10).
  # EOS: jp z (10), ld a,127 (7), ... need 13T + jump? use 7+? 
  # implement normal and eos with same 34T: 10 +10+4+10 vs 10+7+7+10.
  raise AssertionError('replace eos timing')
 if s=='eos34':
  end=im.unique('eos');join=im.unique('eos_join');im.jp(end,'z');im.op('inc iy',0xfd,0x23);im.op('nop',0);im.jp(join);im.label(end);im.op('ld a,127',0x3e,127);im.op('cp 127',0xfe,127);im.jp(join);im.label(join)
 elif s=='pcm_quant':
  end=im.unique('pcm_eos');join=im.unique('pcm_join');im.jp(end,'nc');im.op('inc iy',0xfd,0x23);im.op('inc iy',0xfd,0x23);im.op('rrca',0x0f);im.op('rrca',0x0f);im.op('or ixh',0xdd,0xb4);im.op('ld l,a',0x6f);im.op(f'ld h,{FRAC}',0x26,FRAC);im.op('ld a,(hl)',0x7e);im.op('add a,ixl',0xdd,0x85);im.jp(join);im.label(end);im.op('ld a,127',0x3e,127);emitpad(im,pad(55)[1]);im.jp(join);im.label(join)
 elif s=='sign':
  pos=im.unique('positive');join=im.unique('sign_join');im.jp(pos,'nc');im.op('neg',0xed,0x44);im.op('ld d,16',0x16,16);im.jp(join);im.label(pos);im.op('ld d,0',0x16,0);im.op('nop',0);im.op('nop',0);im.jp(join);im.label(join)
 else:raise ValueError(s)

def actions(p):
 if p==7:
  return next_sample()+lookup(0)
 return (pcm_prefetch() if MODE=='pcm10' and p==5 else pcm_complete() if MODE=='pcm10' and p==6 else [])+lookup(p+1)

def split(a,w):
 best=None
 for k in range(len(a)):
  x=w-12-sum(z[0] for z in a[:k]);y=320-w-12-sum(z[0] for z in a[k:]);u,v=pad(x),pad(y)
  if u is None or v is None:continue
  z=(u[0]+v[0],k,u[1],v[1]);
  if best is None or z[0]<best[0]:best=z
 assert best is not None,(w,a)
 return best

def table(patterns):
 assert patterns.shape==(255,8) and np.array_equal(patterns[::-1],320-patterns) and np.all(patterns[127]==160)
 ids=np.searchsorted(W,patterns[127:]);assert np.array_equal(np.array(W)[ids],patterns[127:]);pk=((ids[:,::2]<<4)|ids[:,1::2]).astype(np.uint8)
 assert pk.tobytes()==(ROOT/'pwm255-half.bin').read_bytes()
 return pk.T.copy().tobytes()

def build(levels,out,patterns=None,pcm=None):
 global MODE
 MODE="pcm10" if pcm is not None else "index"
 if patterns is None:patterns=np.load(ROOT/'pwm255.npy')
 levels=np.asarray(levels);assert levels.ndim==1 and np.all((levels>=0)&(levels<255))
 out=Path(out);out.parent.mkdir(parents=True,exist_ok=True);im=Image();im.label('reset');im.op('di',0xf3);im.op('ld bc,$1000',1,0,16);im.op('ld sp,0',0x31,0,0);im.addr('ld iy,',bytes([0xfd,0x21]),'stream');im.jp('start');assert im.pc<=256;im.align(256);im.label('patterns_transposed');im.data(table(patterns));assert im.pc==DISP*256
 # table bytes patched after generation, textual asm uses labels.
 lo,hi=im.pc,im.pc+256;im.label('dispatch_low');loline=len(im.lines);im.data(bytes(256));im.label('dispatch_high');hiline=len(im.lines);im.data(bytes(256));assert im.pc==0x500
 map_size=0
 if pcm is not None:
  im.label('pcm_map');mp=(ROOT/'pcm-to-pwm255.bin').read_bytes();im.data(mp);assert im.pc==FRAC*256
  # The two-bit fraction in the top bits chooses the field from the packed
  # delta byte (six low bits). The zero fraction always adds zero.
  im.label('fraction_unpack');im.data(bytes(0 if f==0 else (d>>(2*(f-1)))&3 for f in range(4) for d in range(64)));map_size=768
 im.label('start');
 for a in (pcm_prefetch()+pcm_complete() if pcm is not None else [])+next_sample()+lookup(0):emit(im,a)
 schedules=[]
 for p in range(8):
  a=actions(p);assert sum(z[0] for z in a)<=296
  for j,w in enumerate(W):
   im.label(f'p{p}_w{j}');_,k,u,v=split(a,w);im.op('out (c),b',0xed,0x41)
   for z in a[:k]:emit(im,z)
   emitpad(im,u);im.op('out (c),c',0xed,0x49)
   for z in a[k:-1]:emit(im,z)
   emitpad(im,v);emit(im,a[-1]);schedules.append((p,w,k,u,v))
 dispatch=[im.labels[f'p{p}_w{(10-j if sign else j) if j<=10 else 5}'] for p in range(8) for sign in range(2) for j in range(16)]
 low=bytes(v&255 for v in dispatch);high=bytes(v>>8 for v in dispatch);im.b[lo:lo+256]=low;im.b[hi:hi+256]=high
 for off,data in ((loline,low),(hiline,high)):
  im.lines[off:off+16]=['    db '+','.join(f'${x:02x}' for x in data[i:i+16]) for i in range(0,256,16)]
 im.label('stream');core=im.pc;assert core+2<=16384
 if pcm is None:payload=levels.astype(np.uint8).tobytes();eos=b'\xff'
 else:
  pcm=np.asarray(pcm,dtype=np.int16);assert len(pcm)==len(levels) and np.all((-512<=pcm)&(pcm<512));v=np.empty((len(pcm),2),np.uint8);v[:,0]=((pcm//4)&255).astype(np.uint8);v[:,1]=pcm&3;payload=v.tobytes();eos=b'\0\xff'
 im.data(payload+eos);used=im.pc;assert used<=65536
 rom=im.finish();out.with_suffix('.bin').write_bytes(rom+bytes(65536-used));out.with_suffix('.asm').write_text('\n'.join(im.lines+[f'    defs 65536-$,0'])+'\n');out.with_suffix('.idx').write_bytes(levels.astype(np.uint8).tobytes());out.with_suffix('.widths').write_bytes(patterns[np.r_[levels.astype(int),127,127]].astype('<u2').tobytes());out.with_suffix('.json').write_text(json.dumps(dict(core_bytes_including_eos=core+len(eos),code_bytes=core-1280-map_size,pcm_map_bytes=map_size,mode=MODE,pattern_bytes=512,dispatch_bytes=512,boot_page_bytes=256,stream_bytes=len(payload),occupied_rom=used,rom_size=65536,pcm_hz=7812.5,pwm_hz=62500,clock_hz=20000000,bitrate_kbps=62.5*(2 if pcm is not None else 1),stream_address=core,samples=len(levels),seconds=len(levels)/7812.5,entry_addresses=[[im.labels[f'p{p}_w{j}'] for j in range(11)] for p in range(8)]),indent=2));print(out,core,used,flush=True)
 return core
if __name__=='__main__':
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('indices',help='raw bytes 0..254, no EOS');ap.add_argument('output',type=Path);a=ap.parse_args();build(np.fromfile(a.indices,np.uint8),a.output)
