"""Faster lossless-equivalent desktop LPX3 VBR encoder backend.

Expensive static input analysis is computed once per clip, reused for every
lambda. Candidate quantizer scoring is fused in Numba, with no per-candidate
PCM/quantizer array allocations. Final chosen candidate is generated by the
unaltered reference _encode_trial for byte-identical output.
"""
from pathlib import Path
import json,struct,re,sys
import numpy as np
from numba import njit
sys.path.insert(0,str(Path(__file__).resolve().parents[2]/'tools'))
from level_policy import relative_energy_floor
from pack_lpx3_avr import prepare_frames,coeff_pack,pack_bits_lsb,HEADER

@njit(cache=True)
def _trial_sse(xq,aq,hinit,prevd,pre,step,bits):
    hist=hinit.copy();prev=prevd;n=len(xq);tot=0
    maxq=(1<<(bits-1))-1;minq=-(1<<(bits-1))
    for j in range(n):
        acc=0
        for k in range(10):acc+=(int(aq[j,k])*int(hist[k]))>>12
        preterm=(pre*prev)>>14
        needed=int(xq[j])-preterm+acc
        val=(needed+step//2)//step if needed>=0 else -((-needed+step//2)//step)
        if val<minq:val=minq
        elif val>maxq:val=maxq
        pred=val*step-acc
        if pred>32767:pred=32767
        if pred < -32767:pred=-32767
        for k in range(9,0,-1):hist[k]=hist[k-1]
        hist[0]=pred
        prev=pred+preterm
        if prev>32767:prev=32767
        elif prev<-32767:prev=-32767
        clipped=prev
        if clipped>16384:clipped=16384
        elif clipped<-16384:clipped=-16384
        e=int(clipped)-int(xq[j]);tot+=e*e
    return tot

@njit(cache=True)
def _best_block(xq,aq,hist,prevd,pre,steps,codes,counts,energy,lam):
    n=len(xq)
    best=float('inf');best_bits=0;best_sc=0
    for bi in range(4):
        bits=bi+3
        for ix in range(counts[bi]):
            sc=codes[bi,ix]
            step=int(steps[sc])
            if step<=0:continue
            loss=_trial_sse(xq,aq,hist,prevd,pre,step,bits)
            val=float(loss)/n/energy+lam*(bits-3)
            # Stable first-in-search-order tie breaking from reference.
            if val<best:
                best=val;best_bits=bits;best_sc=sc
    return best_bits,best_sc

class Prepared:
    def __init__(self, x,analysis,coeff_trace,source):
        a=json.loads(Path(analysis).read_text());self.pre=round(float(a['meta']['pre'])*16384)
        original=Path(source).read_bytes()
        if len(original)<24:raise ValueError('source LPX3 truncated')
        magic,ver,bits,rate,count,base,block,bright,nblocks=struct.unpack_from('<4sBBHIIHHI',original)
        if magic!=b'LPX3' or ver!=1 or bits not in (2,3,4) or rate!=8000 or count!=len(x) or block!=80:
            raise ValueError('source LPX3 header does not match input 8kHz WAV')
        x=np.asarray(x,dtype=np.float64)
        self.xq=np.clip(np.rint(x*16384),-16384,16384).astype(np.int32)
        qcoeff=np.loadtxt(coeff_trace,delimiter=',')
        assert np.array_equal(qcoeff[:,0],np.arange(len(qcoeff))*20)
        self.co=np.repeat(qcoeff[:,1:].astype(np.int32),20,axis=0)[:len(x)]
        assert len(self.co)==len(x)
        self.framecodes=prepare_frames(a['lsfFrame'],bits=10,lsf=True)
        assert len(self.framecodes)==(len(x)+159)//160
        ss=(Path(__file__).resolve().parents[2]/'src'/'scale_table.inc').read_text().split('\n',1)[1]
        self.steps=np.asarray([int(z) for z in re.findall(r'\b\d+\b',ss)],dtype=np.int32)
        assert len(self.steps)==256
        # Vectorized EXACT reproduction of target fixed-point LPC residual.
        old=np.concatenate((np.zeros(1,dtype=np.int64),self.xq[:-1].astype(np.int64)))
        xp=self.xq.astype(np.int64)-((int(self.pre)*old)>>14)
        res=xp.copy()
        for k in range(10):
            prior=np.zeros(len(x),dtype=np.int64)
            prior[k+1:]=xp[:len(x)-k-1]
            res+=(self.co[:,k].astype(np.int64)*prior)>>12
        self.blocks=[]
        floor=relative_energy_floor(self.xq)
        for st in range(0,len(x),80):
            en=min(st+80,len(x));target=self.xq[st:en];n=len(target)
            rs=res[st:en]
            rms=max(1.0,float(np.sqrt(np.mean(np.square(np.asarray(rs,dtype=np.float64))))))
            energy=max(floor,float(np.mean(target.astype(np.float64)**2)))
            codes=np.zeros((4,16),dtype=np.int32);counts=np.zeros(4,dtype=np.int32)
            for bi,bits in enumerate((3,4,5,6)):
                nominal=rms/max(1,(1<<(bits-1))-.5)
                chosen=[]
                for t in (.3,.4,.5,.6,.75,.9,1.,1.12,1.3,1.55,1.85,2.25,2.9,3.7,5.,7.):
                    z=nominal*t
                    cb=int(round(128+16*np.log2(max(1.0,z)/16.384)))
                    chosen.append(max(0,min(255,cb)))
                selected=sorted(set(chosen));counts[bi]=len(selected)
                codes[bi,:len(selected)]=selected
            self.blocks.append((st,en,energy,codes,counts))


def make_fast(x,analysis,coeff_trace,source,dest,lam,only=None,context=None,block_lambdas=None):
    from encode_vbr_fixedexact import _encode_trial
    if only is not None:
        # Fixed-width diagnostic rarely used; preserve old behavior.
        from encode_vbr_fixedexact import make
        return make(x,analysis,coeff_trace,source,dest,lam,only,fast=False)
    ctx=context if context is not None else Prepared(x,analysis,coeff_trace,source)
    if len(ctx.xq)!=len(x) or not np.array_equal(
        ctx.xq,np.clip(np.rint(np.asarray(x,dtype=np.float64)*16384),-16384,16384).astype(np.int32)):
        raise ValueError('reused VBR context does not match input PCM')
    if block_lambdas is not None and len(block_lambdas)!=len(ctx.blocks):
        raise ValueError('One lambda is required for each 80-sample block')
    hist=np.zeros(10,np.int32);prevd=0
    qpack=[];modes=[];scales=[];blockLoss=[];reference=[]
    for bi,(st,en,energy,codes,counts) in enumerate(ctx.blocks):
        local_lambda=float(block_lambdas[bi]) if block_lambdas is not None else float(lam)
        bits,sc=_best_block(ctx.xq[st:en],ctx.co[st:en],hist,prevd,ctx.pre,
                            ctx.steps,codes,counts,energy,local_lambda)
        if bits==0:raise ValueError('No encoding options for block')
        q,pcm,loss,hh,dd=_encode_trial(ctx.xq[st:en],ctx.co[st:en],hist,prevd,
                                        ctx.pre,int(ctx.steps[sc]),int(bits))
        hist=hh;prevd=dd
        modes.append(int(bits));scales.append(int(sc));qpack.append(q)
        reference.extend(pcm.tolist());blockLoss.append(float(loss/(en-st)))
    out=bytearray(HEADER.pack(b'L3AV',1,3,8000,len(x),ctx.pre,0,160,80));old=None
    for fi,f in enumerate(ctx.framecodes):
        out.extend(coeff_pack(f,old,10,lsf=True));old=f
        for sub in range(2):
            i=fi*2+sub
            if i>=len(qpack):continue
            out.extend((modes[i],scales[i]));out.extend(pack_bits_lsb(qpack[i],modes[i]))
    dest=Path(dest);dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(out)
    np.asarray(reference,dtype='u1').tofile(str(dest)+'.exact.pcm8')
    np.concatenate([np.asarray(q,dtype='i2')-(1<<(b-1)) for q,b in zip(qpack,modes)]).astype('<i2').tofile(str(dest)+'.q_signed.i16')
    return {'bytes':len(out),'samples':len(x),'average_bits':float(np.mean(modes)),
            'mode_counts':{b:modes.count(b) for b in [3,4,5,6]},'lambda':lam,'only_mode':only,
            'step_table':'Q14 exact','note':'machine C++ decoder and integer model must produce exactly the same pcm8'}
