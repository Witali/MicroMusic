#!/usr/bin/env python3
"""Bind the known 27-case regression and exact prior V3 outputs, without encoding.

Former held-out labels become known development cases. Private receipts retain
their original generation hash and historical timing; they are never relabeled
as newly generated by the current baseline binary.
"""
import argparse
from pathlib import Path
import shutil
import study as s

c = s.c


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--previous-manifest", required=True)
    parser.add_argument("--previous-v3-results", required=True)
    parser.add_argument("--baseline-build", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    previous = Path(args.previous_manifest).resolve()
    old = c.json_read(previous)
    results = Path(args.previous_v3_results).resolve()
    out = c.private_path(args.output, fresh=True)
    if (len(old["source_records"]) != 27 or len(old["jobs"]) != 108
            or {job["sample_rate"] for job in old["jobs"]} != {8000}
            or {job["mode"] for job in old["jobs"]} != {"p4", "p6", "k3", "k8"}):
        raise ValueError("Expected the complete known 27-case/four-profile regression")
    out.mkdir(parents=True)
    reference = out / "baseline-reference"
    reference.mkdir()
    jobs = [dict(job, split="tuning" if job["kind"] == "speech" else "controls",
                 former_regression_split=job["split"]) for job in old["jobs"]]
    records = [dict(row, split="tuning" if row["kind"] == "speech" else "controls",
                    former_regression_split=row["split"]) for row in old["source_records"]]
    for name in {job["target"] for job in jobs}:
        job = next(job for job in jobs if job["target"] == name)
        if c.digest(previous.parent / name) != job["target_sha256"]:
            raise ValueError("Known regression prepared reference changed")
        shutil.copyfile(previous.parent / name, out / name)
    generation_hashes = set()
    for job in jobs:
        name = job["job_id"]
        path = results / (name + ".json")
        original = c.json_read(path)
        for field in ("mode", "sample_rate", "samples", "calls", "auto_quiet", "normalize",
                      "size_allowance_percent", "target_sha256", "kind"):
            if original["job"][field] != job[field]:
                raise ValueError("Known V3 output belongs to different settings or input")
        for suffix, key in ((".lpx", "stream_sha256"), (".s16le", "pcm_sha256"), (".u8", "pwm_sha256")):
            source = results / (name + suffix)
            if c.digest(source) != original[key]:
                raise ValueError("Known V3 stream/decoded output binding changed")
            shutil.copyfile(source, reference / source.name)
        receipt = {key: value for key, value in original.items() if key not in
                   ("admission", "speech_safety_admission", "spectral_admission", "v2_admission",
                    "baseline_receipt_sha256", "admission_scope")}
        receipt.update(phase="baseline", job=job, original_generation_phase=original["phase"],
                       original_generation_receipt_sha256=c.digest(path),
                       baseline_equivalence_commit=s.BASELINE, previous_v3_reference_reused=True,
                       baseline_api_timing_is_historical=True)
        generation_hashes.add(original["encoder_sha256"])
        c.json_write(reference / (name + ".json"), receipt)
    manifest = {"schema": 1, "set": "lowrate_known_regression", "matrix_partition": "regression_108",
                "jobs": jobs, "source_records": records, "previous_manifest_sha256": c.digest(previous),
                "baseline_commit": s.BASELINE, "lowrate_protocol_sha256": c.digest(s.HERE / "PROTOCOL.md"),
                "lowrate_preparer_sha256": c.digest(s.__file__), "regression_preparer_sha256": c.digest(__file__),
                "baseline_reference_generation_hashes": sorted(generation_hashes),
                "baseline_reference_scope": "Exact known V3 bindings; generation and historical timing retained. All speech is development/regression, never a new holdout.",
                **c.study_metadata(args.baseline_build)}
    c.json_write(out / "manifest-private.json", manifest)
    c.json_write(reference / "run-private.json", {"schema": 1, "phase": "baseline", "completed": len(jobs),
                 "prospective_jobs": len(jobs), "job_receipts": [job["job_id"] + ".json" for job in jobs],
                 "manifest_sha256": c.digest(out / "manifest-private.json"),
                 "encoder_generation_hashes": sorted(generation_hashes), "reference_reused": True})
    print({"stage": "known_regression_reference_bound", "cases": 27, "jobs": 108,
           "new_independent_holdout": False, "all_target_stream_pcm_pwm_bindings_verified": True})


if __name__ == "__main__":
    main()
