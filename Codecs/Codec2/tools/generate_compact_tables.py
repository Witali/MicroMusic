#!/usr/bin/env python3
"""Extract exact binary32 KISS FFT twiddles/window into Flash-friendly C tables."""
import argparse
import json
import os
from pathlib import Path
import struct
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
import verify_frontend as front
from verify_decoder import function

ROOT = front.ROOT
BUILD = ROOT.parents[1] / 'build/codec2/compact-tables'
DESTINATION = ROOT / 'src/compact_tables.inc'


def generate(cc):
    BUILD.mkdir(parents=True, exist_ok=True)
    source = front.VENDOR / 'src'
    manifest = json.loads((front.VENDOR / 'UPSTREAM.json').read_text())
    for entry in manifest['files']:
        assert front.digest(front.VENDOR / entry['path']) == entry['sha256']
    original = source / 'sine.c'
    text = original.read_text(encoding='utf-8')
    window_source = BUILD / 'window.c'
    window_source.write_bytes((text[:text.index('C2CONST c2const_create(')]
                               + function(original, 'void make_synthesis_window(')).encode('utf-8'))
    program = BUILD / ('tables.exe' if os.name == 'nt' else 'tables')
    front.run([cc, '-O2', '-D_CRT_SECURE_NO_WARNINGS', '-I' + str(source),
               source / 'kiss_fft.c', source / 'kiss_fftr.c', window_source,
               ROOT / 'tests/compact_tables.c', '-o', program, *([] if os.name == 'nt' else ['-lm'])])
    front.run([program, BUILD / 'tables.bin'])
    data = (BUILD / 'tables.bin').read_bytes()
    assert len(data) == 3712
    values = struct.unpack('<928f', data)
    notice = (source / '_kiss_fft_guts.h').read_text(encoding='utf-8').split('*/', 1)[0] + '*/\n'
    output = notice + ('/* Generated by tools/generate_compact_tables.py from pinned Codec2 1.2.0.\n'
        ' * Exact original forward KISS twiddles and Parzen window, stored as C99 hex floats.\n'
        ' * Window copyright David Rowe, LGPL-2.1; see vendor/codec2-1.2.0/src/sine.c.\n */\n')
    for name, start, length in [('compact_twiddle', 0, 512), ('compact_super', 512, 256), ('compact_window', 768, 160)]:
        output += f'static const float {name}[{length}] CODEC2_TABLE_STORAGE = {{\n'
        for at in range(start, start + length, 4):
            output += '    ' + ', '.join(float(x).hex() + 'f' for x in values[at:at + 4]) + ',\n'
        output += '};\n'
    return output.encode('utf-8')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cc', default='clang')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = generate(args.cc)
    if args.check:
        if DESTINATION.read_bytes() != data:
            parser.exit(1, 'Compact tables differ from pinned native generation\n')
    else:
        DESTINATION.write_bytes(data)
