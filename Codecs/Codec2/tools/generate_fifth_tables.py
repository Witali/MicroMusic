#!/usr/bin/env python3
"""Generate fixed-point quadratic x^(1/5) interpolation tables with Decimal."""
import argparse
from decimal import Decimal, localcontext, ROUND_HALF_EVEN
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
DESTINATION=ROOT/'src/fixed_fifth_tables.inc'


def generate(q=11,bits=6):
    assert 8<=q<=23 and 3<=bits<=6
    n=1<<bits
    values=[];curves=[]
    with localcontext() as context:
        context.prec=80
        power=Decimal(1)/5
        scale=Decimal(1<<q)
        integer=lambda x:int(x.to_integral_value(rounding=ROUND_HALF_EVEN))
        for r in range(5):
            f=lambda i:(Decimal(1<<r)*(1+Decimal(i)/n))**power
            nodes=[f(i) for i in range(n+1)]
            values.extend(integer((v-1)*scale) for v in nodes)
            curves.extend(integer(4*(f(Decimal(i)+Decimal('0.5'))-(nodes[i]+nodes[i+1])/2)*scale) for i in range(n))
    assert all(0<=v<=1<<q for v in values)
    assert all(0<=v<=65535 for v in curves)
    for r in range(5):
        for i in range(n):assert values[r*(n+1)+i+1]-values[r*(n+1)+i]>=curves[r*n+i]
    text=('/* Generated by tools/generate_fifth_tables.py, Decimal precision 80.\n'
          ' * Original project data: h_r(t)=(2^r*(1+t))^(1/5), r=0..4.\n'
          ' * Values: (h-1)*2^Q. Curves: 4*(h(mid)-(h(left)+h(right))/2)*2^Q.\n'
          ' * Nearest integer, ties to even. No copied external tables.\n */\n')
    text+=f'#if CODEC2_ROOT_Q != {q} || CODEC2_ROOT_TABLE_BITS != {bits}\n#error Wrong fifth-root table configuration\n#endif\n'
    if q<=15:
        data=values;ctype='uint16_t'
    else:
        data=[(v>>(8*b))&255 for v in values for b in range(3)];ctype='uint8_t'
    for name,data,ctype in [('fifth_value',data,ctype),('fifth_curve',curves,'uint16_t')]:
        text+=f'static const {ctype} {name}[{len(data)}] CODEC2_TABLE_STORAGE = {{\n'
        for at in range(0,len(data),12):text+='    '+', '.join(str(v) for v in data[at:at+12])+',\n'
        text+='};\n'
    return text.encode('utf-8')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--q',type=int,default=11);parser.add_argument('--table-bits',type=int,default=6)
    parser.add_argument('--check',action='store_true');args=parser.parse_args();data=generate(args.q,args.table_bits)
    if args.check:assert DESTINATION.read_bytes()==data
    else:DESTINATION.write_bytes(data)
