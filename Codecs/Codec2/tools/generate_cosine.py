#!/usr/bin/env python3
"""Generate the mathematical Q15 quarter cosine table; no copied vendor data."""
import argparse
import math
from pathlib import Path

DESTINATION = Path(__file__).resolve().parents[1] / 'src/cosine_q15.inc'


def contents():
    values = [int(math.floor(32768 * math.cos(math.pi * i / 320) + 0.5)) for i in range(161)]
    rows = [', '.join(str(x) for x in values[i:i + 12]) for i in range(0, len(values), 12)]
    return ('/* Generated by tools/generate_cosine.py: round(32768*cos(pi*i/320)), i=0..160. */\n'
            'static const uint16_t codec2_cosine_quarter_q15[161] CODEC2_TABLE_STORAGE = {\n    '
            + ',\n    '.join(rows) + '\n};\n').encode('ascii')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        if DESTINATION.read_bytes() != contents():
            parser.exit(1, 'Cosine table differs; regenerate it\n')
    else:
        DESTINATION.write_bytes(contents())
